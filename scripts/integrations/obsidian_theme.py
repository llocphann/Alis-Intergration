#!/usr/bin/env python3
"""Own one Obsidian snippet; preserve active theme, fonts, plugins and other CSS.

Alis owns the ramp, semantic colors, native accent channels and startup tint.
The selected theme and user snippets remain untouched; no Obsidian companion is used.
No note contents are read. Input/output is one JSON document on stdio.
"""
import colorsys,json,os,re,stat,sys,tempfile
sys.dont_write_bytecode = True
from pathlib import Path
SNIPPET='99_Alis_Theme'
LEGACY_SNIPPET='99_Hadalis_Theme'
ASSETS=Path(__file__).resolve().parent
WEIGHTS=[0,.012,.038,.073,.113,.167,.228,.310,.402,.506,.621,.748,.886,1]
def read_json(path,default=None):
 if not path.exists() and default is not None:return default
 value=json.loads(path.read_text())
 if not isinstance(value,dict):raise ValueError('Configuration must be a JSON object')
 return value

def resolve_paths(payload):
 app_config=Path(os.path.expanduser(str(payload.get('applicationConfigPath') or os.environ.get('XDG_CONFIG_HOME',str(Path.home()/'.config'))+'/obsidian')))
 vault=str(payload.get('vaultPath') or '').strip()
 if not vault:
  state=read_json(app_config/'obsidian.json',{})
  vaults=[v for v in state.get('vaults',{}).values() if isinstance(v,dict) and v.get('path')]
  selected=next((v for v in vaults if v.get('open')),vaults[0] if len(vaults)==1 else None)
  if selected:vault=selected['path']
 if not vault:raise ValueError('Choose an Obsidian vault')
 vault=Path(os.path.expanduser(vault)).resolve()
 if not vault.is_dir():raise ValueError('Vault folder does not exist')
 cfg=Path(os.path.expanduser(str(payload.get('configPath') or '.obsidian')))
 if not cfg.is_absolute():cfg=vault/cfg
 cfg=cfg.resolve()
 if not cfg.is_dir():raise ValueError('Obsidian configuration folder does not exist')
 return vault,cfg

def rgb(value):
 value=str(value)
 if not re.fullmatch(r'#[a-fA-F0-9]{6}',value):raise ValueError('Palette colors must be opaque hexadecimal RGB values')
 return tuple(int(value[i:i+2],16)/255 for i in (1,3,5))
def hex_rgb(value):return '#'+''.join(f'{max(0,min(255,round(channel*255))):02x}' for channel in value)
def mix(a,b,weight):return tuple(x+(y-x)*weight for x,y in zip(a,b))
def weights(cfg,appearance):
 # The shell is the sole palette owner. Do not infer weights from arbitrary
 # user CSS or an earlier generated file (which creates feedback/drift).
 return WEIGHTS,'Alis palette'

def native_channels(color):
 h,l,s=colorsys.rgb_to_hls(*color)
 return {'accent-h':f'{h*360:.8f}','accent-s':f'{s*100:.8f}%',
         'accent-l':f'{l*100:.8f}%',
         'color-accent-rgb':', '.join(str(round(v*255)) for v in color)}

def make_css(palette,stops):
 base,ink,accent=(rgb(palette.get(key,'')) for key in ['background','foreground','accent'])
 # Primitive indices always mean darkest -> lightest, even in a light shell.
 if colorsys.rgb_to_hls(*base)[1] <= colorsys.rgb_to_hls(*ink)[1]:
  dark,light=base,ink
  if max(light)-min(light)<.01 and min(light)>.99:light=mix(light,dark,.03)
 else:dark,light=ink,base
 ramp=[hex_rgb(mix(mix(dark,light,t),accent,.055*4*t*(1-t))) for t in stops]
 spec=json.loads((ASSETS/'obsidian_palette.json').read_text())
 lines=['/* Generated by Alis. Disable this snippet to restore the active theme. */',
        'body.theme-dark:not(.theme-light), body.theme-light:not(.theme-dark) {']
 lines += [f'  --cc-p{i:02}: {color} !important;' for i,color in enumerate(ramp)]
 lines += [f'  --cc-accent: {hex_rgb(accent)} !important;','}']
 for mode in ('dark','light'):
  ui_accent=accent if mode=='dark' else mix(rgb(ramp[0]),accent,.38)
  lines.append(f'body.theme-{mode}:not(.theme-{"light" if mode=="dark" else "dark"}) {{')
  lines += [f'  --{key}: {value} !important;' for key,value in native_channels(ui_accent).items()]
  h,_,s=colorsys.rgb_to_hls(*accent)
  for name,shift in spec['states'].items():
   color=colorsys.hls_to_rgb((h+shift/360)%1,.70 if mode=='dark' else .26,max(s,.48))
   legacy={'success':'green','warning':'yellow','danger':'red','info':'cyan'}.get(name,name)
   lines += [f'  --av-state-{name}: {hex_rgb(color)} !important;',
             f'  --color-{legacy}: var(--av-state-{name}) !important;',
             f'  --color-{legacy}-rgb: {", ".join(str(round(v*255)) for v in color)} !important;']
  for name,state in spec['markers'].items():lines.append(f'  --av-marker-{name}: var(--av-state-{state}) !important;')
  for name,state in spec['callouts'].items():
   legacy={'success':'green','warning':'yellow','danger':'red','info':'cyan'}.get(state,state)
   lines.append(f'  --{name}-color: var(--color-{legacy}-rgb) !important;')
  lines.append('}')
 lines += [(ASSETS/'obsidian_colors.css').read_text(),(ASSETS/'obsidian_loading.css').read_text()]
 lines += [f'.callout[data-callout="{name}"] {{ --av-callout-ink: var(--av-state-{state}) !important; }}' for name,state in spec['callouts'].items()]
 return '\n'.join(lines)+'\n'

def owned_legacy(cfg):
 path=cfg/'snippets'/(LEGACY_SNIPPET+'.css')
 return path.is_file() and not path.is_symlink() and path.read_text().startswith('/* Generated by Hadalis.')

def atomic_write(path,data):
 if path.exists() and path.read_bytes()==data:return False
 path.parent.mkdir(parents=True,exist_ok=True)
 mode=stat.S_IMODE(path.stat().st_mode) if path.exists() else 0o600
 fd,name=tempfile.mkstemp(prefix='.'+path.name+'.',dir=path.parent)
 try:
  with os.fdopen(fd,'wb') as stream:
   os.fchmod(stream.fileno(),mode);stream.write(data);stream.flush();os.fsync(stream.fileno())
  os.replace(name,path)
 finally:
  if os.path.exists(name):os.unlink(name)
 return True

def update_enabled(path,enabled,legacy_owned=False):
 # Re-read immediately before merging. Retry if Obsidian saves while the
 # candidate is being prepared; never replace its unrelated preferences.
 for attempt in range(3):
  before=path.read_bytes() if path.exists() else b''
  value=json.loads(before or b'{}')
  if not isinstance(value,dict):raise ValueError('Appearance configuration must be a JSON object')
  entries=value.get('enabledCssSnippets',[])
  if not isinstance(entries,list):raise ValueError('CSS snippet selection must be a list')
  selected=[name for name in entries if name!=SNIPPET and not (legacy_owned and name==LEGACY_SNIPPET)]
  if enabled:selected.append(SNIPPET)
  if selected==entries:return False
  value['enabledCssSnippets']=selected
  data=(json.dumps(value,ensure_ascii=False,indent=2)+'\n').encode()
  if (path.read_bytes() if path.exists() else b'')!=before:continue
  return atomic_write(path,data)
 raise ValueError('Obsidian is updating its appearance; try again')

def execute(payload):
 vault,cfg=resolve_paths(payload);appearance_file=cfg/'appearance.json';appearance=read_json(appearance_file,{})
 stops,profile=weights(cfg,appearance)
 result={'ok':True,'vaultPath':str(vault),'configPath':str(cfg),'activeTheme':appearance.get('cssTheme') or 'Default','profile':profile,'snippetName':SNIPPET,'snippetPath':str(cfg/'snippets'/(SNIPPET+'.css')),'enabled':SNIPPET in appearance.get('enabledCssSnippets',[]),'changed':False}
 action=payload.get('action','inspect')
 if action=='apply':
  target=cfg/'snippets'/(SNIPPET+'.css')
  if target.is_symlink() or (target.exists() and not target.read_text().startswith('/* Generated by Alis.')):
   raise ValueError('The Alis snippet path contains an unowned file; preserve it before applying')
  css=make_css(payload.get('palette',{}),stops)
  changed=atomic_write(cfg/'snippets'/(SNIPPET+'.css'),css.encode())
  result.update(changed=update_enabled(appearance_file,True,owned_legacy(cfg)) or changed,enabled=True)
 elif action=='disable':result.update(changed=update_enabled(appearance_file,False,owned_legacy(cfg)),enabled=False)
 elif action!='inspect':raise ValueError('Unsupported theme action')
 return result
if __name__=='__main__':
 try:
  payload=json.loads(sys.stdin.read(32769))
  if not isinstance(payload,dict):raise ValueError('Request must be an object')
  print(json.dumps(execute(payload),ensure_ascii=False))
 except (OSError,ValueError,TypeError,KeyError) as error:
  print(json.dumps({'ok':False,'error':str(error)}));sys.exit(1)
